import { defaultSchema } from "rehype-sanitize";

// Class names added by remark-gfm for task lists
export const TASK_LIST_CLASS = "contains-task-list";
export const TASK_LIST_ITEM_CLASS = "task-list-item";

// Content rows use leading-6 (1.5rem line-height = 24px at the 16px root font).
const ROW_HEIGHT_PX = 24;

// Compact mode display settings
export const COMPACT_MODE_CONFIG = {
  previewRows: 6, // collapsed preview height, in content rows
  triggerRows: 8, // only fold when content is taller than this (2-row buffer over the preview)
  gradientHeight: "h-12", // Tailwind class for the bottom fade overlay (~2 rows)
} as const;

// Height the collapsed preview is clamped to, in pixels.
export const getPreviewMaxHeightPx = () => COMPACT_MODE_CONFIG.previewRows * ROW_HEIGHT_PX;

// Height a memo must exceed before it gets folded at all, in pixels.
export const getCompactTriggerHeightPx = () => COMPACT_MODE_CONFIG.triggerRows * ROW_HEIGHT_PX;

// Whether content of the given rendered height should be collapsed. Kept pure for unit testing.
export const shouldCompactContent = (contentHeightPx: number, triggerHeightPx: number) => contentHeightPx > triggerHeightPx;

export const COMPACT_STATES: Record<"ALL" | "SNIPPET", { textKey: string; next: "ALL" | "SNIPPET" }> = {
  ALL: { textKey: "memo.show-more", next: "SNIPPET" },
  SNIPPET: { textKey: "memo.show-less", next: "ALL" },
};

const TRUSTED_IFRAME_SRC_PATTERNS = [
  /^https:\/\/www\.youtube\.com\/embed\/[^?#]+(?:\?.*)?$/i,
  /^https:\/\/www\.youtube-nocookie\.com\/embed\/[^?#]+(?:\?.*)?$/i,
  /^https:\/\/player\.vimeo\.com\/video\/[^?#]+(?:\?.*)?$/i,
  /^https:\/\/open\.spotify\.com\/embed\/[^?#]+(?:\?.*)?$/i,
  /^https:\/\/w\.soundcloud\.com\/player\/?(?:\?.*)?$/i,
  /^https:\/\/www\.loom\.com\/embed\/[^?#]+(?:\?.*)?$/i,
  /^https:\/\/www\.google\.com\/maps\/embed(?:\/[^?#]*)?(?:\?.*)?$/i,
  /^https:\/\/(?:app\.)?diagrams\.net\/(?:[^?#]+)?(?:\?.*)?$/i,
  /^https:\/\/(?:www\.)?draw\.io\/(?:[^?#]+)?(?:\?.*)?$/i,
];

const KATEX_INLINE_CLASS_NAMES = ["language-math", "math-inline"] as const;
const KATEX_BLOCK_CLASS_NAMES = ["language-math", "math-display"] as const;
const SPAN_CLASS_NAMES = ["mention", "tag"] as const;
const MARK_CLASS_NAMES = ["highlight", "highlight-yellow", "highlight-pink"] as const;
const INPUT_ATTRIBUTES = [...(defaultSchema.attributes?.input || []), ["checked", true]] as const;

export const isTrustedIframeSrc = (src: string): boolean => TRUSTED_IFRAME_SRC_PATTERNS.some((pattern) => pattern.test(src));

/**
 * Sanitization schema for markdown HTML content.
 * Extends the default schema to allow:
 * - KaTeX marker classes used before trusted KaTeX rendering runs
 * - Mention/tag metadata generated by trusted remark plugins
 * - iframe embeds only from trusted video providers
 *
 * This prevents XSS attacks while preserving math rendering functionality.
 */
export const SANITIZE_SCHEMA = {
  ...defaultSchema,
  // Don't re-prefix `id`/`name` attributes. remark-rehype already namespaces footnote ids with
  // `user-content-` and emits matching `#user-content-…` hrefs; the default schema's clobbering
  // would prepend a *second* `user-content-` to the ids only (not the hrefs), breaking in-page
  // navigation. Leaving ids untouched keeps footnote (and heading) anchors pointing at real targets.
  clobber: [],
  attributes: {
    ...defaultSchema.attributes,
    img: [...(defaultSchema.attributes?.img || []), "height", "width"],
    input: INPUT_ATTRIBUTES,
    // `data-task-status` carries the extended checkbox marker (`- [/]`, `- [?]`, …)
    // from remark-task-status through to the list item renderer; `data-counter`
    // carries a `- [N]` click counter's value and position (see remark-counter).
    li: [...(defaultSchema.attributes?.li || []), "dataTaskStatus", "dataCounter", "dataCounterIndex"],
    // `data-sheet-id` carries a sheets block's style-overlay anchor from the fence
    // info string (```sheets id=xxx) through to CodeBlock; see remark-sheets-id.
    code: [
      ...(defaultSchema.attributes?.code || []),
      ["className", ...KATEX_INLINE_CLASS_NAMES, ...KATEX_BLOCK_CLASS_NAMES],
      "dataSheetId",
    ],
    span: [...(defaultSchema.attributes?.span || []), ["className", ...SPAN_CLASS_NAMES], ["aria*"], ["data*"]],
    mark: [["className", ...MARK_CLASS_NAMES]],
    blockquote: [...(defaultSchema.attributes?.blockquote || []), ["data*"]],
    iframe: [
      ["src", ...TRUSTED_IFRAME_SRC_PATTERNS],
      "width",
      "height",
      "frameborder",
      "allowfullscreen",
      "allow",
      "title",
      "referrerpolicy",
      "loading",
    ],
  },
  tagNames: [...(defaultSchema.tagNames || []), "iframe", "mark"],
  protocols: {
    ...defaultSchema.protocols,
    src: ["https"],
  },
};
